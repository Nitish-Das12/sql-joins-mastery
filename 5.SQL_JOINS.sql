-- LEFT JOIN
SELECT ORDERS_J.OID , ORDERS_J.AMOUNT , CUSTOMERS_J.NAME -- 15
FROM CUSTOMERS_J
LEFT JOIN ORDERS_J
ON ORDERS_J.CID = CUSTOMERS_J.CID;

SELECT CONCAT(FIRST_NAME , " ", LAST_NAME) AS FULL_NAME , TITLE AS MOVIES -- 16
FROM MEMBERS
LEFT JOIN MOVIES
ON MOVIES.MOVIE_ID = MEMBERS.MOVIE_ID;

