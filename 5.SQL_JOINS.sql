CREATE DATABASE SQL_JOINS;
USE SQL_JOINS;

CREATE TABLE CUSTOMERS_J (
    CID INT PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL
);

CREATE TABLE ORDERS_J (
    OID INT PRIMARY KEY,
    CID INT,
    AMOUNT DECIMAL(10,2)
);

CREATE TABLE MOVIES (
    MOVIE_ID INT PRIMARY KEY,
    TITLE VARCHAR(50)
);

CREATE TABLE MEMBERS (
    MEMBER_ID INT PRIMARY KEY,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    MOVIE_ID INT
);

CREATE TABLE MEALS (
    MEAL_ID INT PRIMARY KEY,
    MEALNAME VARCHAR(50),
    RATE DECIMAL(10,2)
);

CREATE TABLE DRINKS_J (
    DRINK_ID INT PRIMARY KEY,
    DRINKNAME VARCHAR(50),
    RATE DECIMAL(10,2)
);

CREATE TABLE STAFF_SELF (
    EMP_ID INT PRIMARY KEY,
    NAME VARCHAR(50),
    MGR_ID INT
);

